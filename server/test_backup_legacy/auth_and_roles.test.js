test('Role enforcement: Customer cannot access Provider or Admin endpoints', async () => {
  const regRes = await request(app)
    .post('/api/auth/register')
    .send({
      name: 'Customer Alice',
      email: 'alice@example.com',
      password: 'Password123',
      role: 'customer',
      city: 'sangli'
    });
  const token = regRes.body.token;

  // 1. Allowed on customer endpoint
  const custRes = await request(app)
    .get('/api/users/customer-zone')
    .set('Authorization', `Bearer ${token}`);
  assert.equal(custRes.status, 200);

  // 2. Denied on provider endpoint
  const provRes = await request(app)
    .get('/api/users/provider-zone')
    .set('Authorization', `Bearer ${token}`);
  assert.equal(provRes.status, 403);
  assert.ok(provRes.body.error.includes('Access denied'));

  // 3. Denied on admin endpoint
  const adminRes = await request(app)
    .get('/api/users/admin-zone')
    .set('Authorization', `Bearer ${token}`);
  assert.equal(adminRes.status, 403);
});

