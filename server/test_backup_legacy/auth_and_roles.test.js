test('Health check endpoint returns HTTP 503 and degraded status when database is disconnected', async () => {
  // Temporarily disconnect Mongoose
  await mongoose.disconnect();

  const res = await request(app).get('/api/health');
  assert.equal(res.status, 503);
  assert.equal(res.body.status, 'degraded');
  assert.equal(res.body.services.server, 'operational');
  assert.equal(res.body.services.database, 'disconnected');

  // Reconnect to memory server for subsequent tests
  await mongoose.connect(mongoServer.getUri());
});

test('pingDatabase helper confirms healthy database and fails safely on disconnection', async () => {
  const isHealthy = await pingDatabase(1000);
  assert.equal(isHealthy, true);

  await mongoose.disconnect();
  const isHealthyDisconnected = await pingDatabase(500);
  assert.equal(isHealthyDisconnected, false);

  // Restore connection
  await mongoose.connect(mongoServer.getUri());
});

