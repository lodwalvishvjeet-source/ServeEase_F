test('User can update allowed profile fields (name, phone) but cannot elevate role or change status', async () => {
  const regRes = await request(app)
    .post('/api/auth/register')
    .send({
      name: 'Regular Customer',
      email: 'regular@example.com',
      password: 'Password123',
      role: 'customer',
      city: 'sangli'
    });
  const token = regRes.body.token;

  // Attempt to update name and sneakily elevate role to admin
  const patchRes = await request(app)
    .patch('/api/users/me')
    .set('Authorization', `Bearer ${token}`)
    .send({
      name: 'Updated Customer Name',
      phoneNumber: '+91 9123456789',
      role: 'admin', // Tamper attempt!
      status: 'suspended', // Tamper attempt!
      passwordHash: 'hacked_hash' // Tamper attempt!
    });

  assert.equal(patchRes.status, 200);
  assert.equal(patchRes.body.user.name, 'Updated Customer Name');
  assert.equal(patchRes.body.user.phoneNumber, '+91 9123456789');
  assert.equal(patchRes.body.user.role, 'customer', 'Role must remain customer and ignore tampering');
  assert.equal(patchRes.body.user.status, 'active', 'Status must remain active and ignore tampering');

  // Verify in MongoDB directly
  const inDb = await User.findOne({ email: 'regular@example.com' });
  assert.equal(inDb.role, 'customer');
  assert.equal(inDb.status, 'active');
});

