test('Customer registration succeeds and returns safe user profile without passwordHash', async () => {
  const res = await request(app)
    .post('/api/auth/register')
    .send({
      name: 'Rohan Sharma',
      email: 'rohan.sharma@example.com',
      password: 'SecurePassword123',
      role: 'customer',
      city: 'sangli',
      phoneNumber: '+91 9876543210'
    });

  assert.equal(res.status, 201);
  assert.equal(res.body.success, true);
  assert.equal(res.body.user.name, 'Rohan Sharma');
  assert.equal(res.body.user.email, 'rohan.sharma@example.com');
  assert.equal(res.body.user.role, 'customer');
  assert.equal(res.body.user.city, 'sangli');
  assert.equal(res.body.user.passwordHash, undefined, 'passwordHash must never be exposed');
  assert.ok(res.body.token, 'A valid JWT token should be returned');

  // Check HttpOnly cookie is set
  const cookieHeader = res.headers['set-cookie'];
  assert.ok(cookieHeader, 'Set-Cookie header should be present');
  assert.ok(cookieHeader[0].includes('HttpOnly'), 'Cookie must have HttpOnly flag');

  // Verify persistence in MongoDB
  const savedUser = await User.findOne({ email: 'rohan.sharma@example.com' }).select('+passwordHash');
  assert.ok(savedUser);
  assert.notEqual(savedUser.passwordHash, 'SecurePassword123', 'Password must not be stored in plaintext');
  assert.ok(savedUser.passwordHash.startsWith('$2'), 'Password hash must be generated by bcrypt');
});

